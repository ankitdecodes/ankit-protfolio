import { useMemo, useState, type FormEvent } from 'react'
import { Search } from 'lucide-react'
import { projects } from '../../content/projects'
import { sampleQuestions } from '../../content/corpus'
import { composeAnswer, embedQuery, projectPCA, retrieve, tokenize } from '../../lib/rag'
import { LabFrame } from './LabFrame'
import { labIndex } from './labIndex'

type Stage = 'tokenize' | 'embed' | 'retrieve' | 'generate'

const STAGES: { id: Stage; label: string; caption: string }[] = [
  { id: 'tokenize', label: 'Tokenize', caption: 'Normalise and split the question' },
  { id: 'embed', label: 'Embed', caption: 'Weight terms into a vector (TF-IDF)' },
  { id: 'retrieve', label: 'Retrieve', caption: 'Rank chunks by cosine similarity' },
  { id: 'generate', label: 'Generate', caption: 'Compose a cited answer' },
]

const PALETTE = ['#f2f0e9', '#c7ff69', '#9b8fff', '#7cc7ff', '#ffb46b']

export function RetrievalExplorer() {
  const [draft, setDraft] = useState(sampleQuestions[0]!)
  const [query, setQuery] = useState(sampleQuestions[0]!)
  const [stage, setStage] = useState<Stage>('retrieve')

  const projection = useMemo(() => projectPCA(labIndex.vectors), [])
  const tokens = tokenize(query)
  const vector = embedQuery(labIndex, query)
  const hits = retrieve(labIndex, query, 3)
  const answer = composeAnswer(labIndex, query, hits)
  const q = projection.project(vector)

  const sources = projects.map((p) => p.id)
  const colorOf = (sourceId: string) => PALETTE[Math.max(0, sources.indexOf(sourceId)) % PALETTE.length]!

  const xs = [...projection.points.map((p) => p.x), q.x]
  const ys = [...projection.points.map((p) => p.y), q.y]
  const [minX, maxX, minY, maxY] = [Math.min(...xs), Math.max(...xs), Math.min(...ys), Math.max(...ys)]
  const sx = (x: number) => 20 + ((x - minX) / (maxX - minX || 1)) * 360
  const sy = (y: number) => 20 + ((y - minY) / (maxY - minY || 1)) * 220

  const submit = (e: FormEvent) => {
    e.preventDefault()
    if (draft.trim()) setQuery(draft.trim())
  }

  return (
    <LabFrame
      name="retrieval.pipeline"
      badge="Real retrieval · no LLM"
      note="Vectors are TF-IDF, not neural embeddings, and the answer is extracted from retrieved text rather than generated by a language model. The corpus is this portfolio’s own case studies."
    >
      <form onSubmit={submit} className="flex flex-col gap-3 border-b border-line p-4 sm:flex-row sm:p-6">
        <label htmlFor="rag-q" className="sr-only">
          Ask a question about the projects
        </label>
        <input
          id="rag-q"
          value={draft}
          onChange={(e) => setDraft(e.target.value)}
          className="h-11 flex-1 rounded-lg border border-line bg-bg px-4 text-sm text-fg placeholder:text-subtle focus:border-accent/60 focus:outline-none focus-visible:outline-2 focus-visible:outline-accent"
          placeholder="Ask about the projects…"
        />
        <button type="submit" className="inline-flex h-11 items-center justify-center gap-2 rounded-lg bg-fg px-4 text-sm font-medium text-bg hover:bg-accent">
          <Search className="size-4" aria-hidden /> Retrieve
        </button>
      </form>
      <div className="flex flex-wrap gap-1.5 border-b border-line px-4 py-3 sm:px-6">
        {sampleQuestions.map((s) => (
          <button
            key={s}
            type="button"
            onClick={() => {
              setDraft(s)
              setQuery(s)
            }}
            className="rounded-md border border-line px-2.5 py-1 text-xs text-muted transition-colors hover:border-line-strong hover:text-fg"
          >
            {s}
          </button>
        ))}
      </div>

      <ol className="grid grid-cols-2 gap-px bg-line sm:grid-cols-4">
        {STAGES.map((s, i) => (
          <li key={s.id} className="bg-bg">
            <button
              type="button"
              aria-pressed={stage === s.id}
              onClick={() => setStage(s.id)}
              className="w-full p-4 text-left transition-colors hover:bg-surface aria-pressed:bg-surface-2"
            >
              <span className={`font-mono text-xs ${stage === s.id ? 'text-ai' : 'text-subtle'}`}>0{i + 1}</span>
              <span className="mt-1 block text-sm font-medium text-fg">{s.label}</span>
              <span className="mt-0.5 block text-xs text-subtle">{s.caption}</span>
            </button>
          </li>
        ))}
      </ol>

      <div className="grid lg:grid-cols-12">
        <div className="border-b border-line p-4 sm:p-6 lg:col-span-7 lg:border-r lg:border-b-0" aria-live="polite">
          {stage === 'tokenize' && (
            <div>
              <p className="text-sm text-muted">Lower-cased, punctuation stripped, stopwords removed, light stemming:</p>
              <ul className="mt-3 flex flex-wrap gap-1.5">
                {tokens.map((t, i) => (
                  <li key={`${t}-${i}`} className="rounded border border-line bg-surface-2 px-2 py-0.5 font-mono text-xs text-fg">
                    {t}
                  </li>
                ))}
              </ul>
            </div>
          )}
          {stage === 'embed' && (
            <div>
              <p className="text-sm text-muted">
                Each known term is weighted by how rare it is across the corpus, then the vector is L2-normalised. Terms
                the corpus has never seen get no weight.
              </p>
              <ul className="mt-3 space-y-1.5">
                {[...vector].sort((a, b) => b[1] - a[1]).map(([term, w]) => (
                  <li key={term} className="grid grid-cols-[7rem_1fr_3rem] items-center gap-3 font-mono text-xs">
                    <span className="truncate text-fg">{term}</span>
                    <span className="h-1.5 rounded-full bg-line">
                      <span className="block h-full rounded-full bg-ai" style={{ width: `${w * 100}%` }} />
                    </span>
                    <span className="text-right text-muted">{w.toFixed(2)}</span>
                  </li>
                ))}
                {vector.size === 0 && <li className="text-sm text-subtle">No query terms appear in the corpus.</li>}
              </ul>
            </div>
          )}
          {stage === 'retrieve' && (
            <ol className="space-y-3">
              {hits.length === 0 && <li className="text-sm text-subtle">No chunk shares a term with this question.</li>}
              {hits.map((h, i) => (
                <li key={h.chunk.id} className="rounded-lg border border-line bg-bg/40 p-3">
                  <div className="flex items-center justify-between gap-3 font-mono text-xs">
                    <span className="text-muted">
                      [{i + 1}] {h.chunk.source} · {h.chunk.kind}
                    </span>
                    <span className="text-ai">cos {h.score.toFixed(3)}</span>
                  </div>
                  <p className="mt-1.5 text-sm leading-relaxed text-fg">{h.chunk.text}</p>
                  <p className="mt-1.5 font-mono text-xs text-subtle">matched: {h.matched.join(', ')}</p>
                </li>
              ))}
            </ol>
          )}
          {stage === 'generate' && (
            <div>
              {answer.length === 0 ? (
                <p className="text-sm text-subtle">Nothing was retrieved, so the system declines to answer instead of guessing.</p>
              ) : (
                <p className="leading-relaxed text-fg">
                  {answer.map((a) => (
                    <span key={a.citation}>
                      {a.text} <sup className="font-mono text-ai">[{a.citation}]</sup>{' '}
                    </span>
                  ))}
                </p>
              )}
              <p className="mt-3 text-xs text-subtle">
                Extractive: the best-matching sentence from each retrieved chunk, with its citation. A production system
                would pass these chunks to an LLM with instructions to cite them.
              </p>
            </div>
          )}
        </div>

        <div className="p-4 sm:p-6 lg:col-span-5">
          <p className="eyebrow">Embedding map · PCA of {labIndex.chunks.length} chunks</p>
          <svg viewBox="0 0 400 260" className="mt-3 w-full rounded-lg border border-line bg-bg/40" role="img" aria-label="Two-dimensional projection of the document vectors with the query and its top matches highlighted.">
            {hits.map((h) => (
              <line
                key={h.chunk.id}
                x1={sx(q.x)}
                y1={sy(q.y)}
                x2={sx(projection.points[h.index]!.x)}
                y2={sy(projection.points[h.index]!.y)}
                stroke="var(--color-ai)"
                strokeOpacity={0.6}
                strokeDasharray="3 3"
              />
            ))}
            {projection.points.map((p, i) => {
              const chunk = labIndex.chunks[i]!
              const hit = hits.some((h) => h.index === i)
              return (
                <circle key={chunk.id} cx={sx(p.x)} cy={sy(p.y)} r={hit ? 5 : 3} fill={colorOf(chunk.sourceId)} opacity={hit ? 1 : 0.45}>
                  <title>{`${chunk.source} · ${chunk.kind}: ${chunk.text}`}</title>
                </circle>
              )
            })}
            <circle cx={sx(q.x)} cy={sy(q.y)} r={7} fill="none" stroke="var(--color-ai)" strokeWidth={2} />
            <circle cx={sx(q.x)} cy={sy(q.y)} r={2.5} fill="var(--color-ai)" />
          </svg>
          <ul className="mt-3 flex flex-wrap gap-x-4 gap-y-1.5 text-xs text-muted">
            {projects.map((p) => (
              <li key={p.id} className="flex items-center gap-1.5">
                <span className="size-2 rounded-full" style={{ background: colorOf(p.id) }} aria-hidden />
                {p.name.split(' —')[0]}
              </li>
            ))}
            <li className="flex items-center gap-1.5">
              <span className="size-2 rounded-full border border-ai" aria-hidden /> your query
            </li>
          </ul>
          <p className="mt-2 font-mono text-xs text-subtle">
            Axes explain {(projection.explained[0] * 100).toFixed(0)}% + {(projection.explained[1] * 100).toFixed(0)}% of
            variance; nearby points share vocabulary, so distances are approximate.
          </p>
        </div>
      </div>
    </LabFrame>
  )
}
